#!/usr/bin/env bun
/**
 * Generate src/lib/caseFolding.generated.ts, Unicode's full case folding (CaseFolding.txt statuses C and
 * F) for a pinned Unicode version. src/lib/promptAnswer.ts folds option names with it for Unicode's
 * compatibility caseless match (Unicode 3.13, D146), which `toUpperCase().toLowerCase()` does not equal.
 *
 *   bun run scripts/generate-case-folding.ts                   # download the pinned CaseFolding.txt, write the table
 *   bun run scripts/generate-case-folding.ts --source <file>   # read a local copy of that file instead
 *   bun run scripts/generate-case-folding.ts --check           # fail if the committed table is stale; never writes
 *
 * Raise UNICODE_VERSION to move to a newer Unicode, then run the script and commit both files.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const UNICODE_VERSION = "17.0.0";
const SOURCE_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/CaseFolding.txt`;
const OUTPUT = join(import.meta.dir, "..", "src", "lib", "caseFolding.generated.ts");

/** `<code point>=<its folding>` entries, hex, from the C and F lines of CaseFolding.txt; throws on a file of another version */
export function caseFoldingEntries(text: string): string[] {
  const version = /^# CaseFolding-(\d+\.\d+\.\d+)\.txt/m.exec(text)?.[1];
  if (version !== UNICODE_VERSION) throw new Error(`CaseFolding.txt is version ${version ?? "unknown"}, not ${UNICODE_VERSION}`);
  const entries: string[] = [];
  for (const line of text.split("\n")) {
    const data = line.replace(/#.*/, "").trim();
    if (!data) continue;
    const [code, status, mapping] = data.split(";").map((field) => field.trim());
    if (status !== "C" && status !== "F") continue;
    if (!code || !mapping) throw new Error(`malformed CaseFolding.txt line: ${line}`);
    entries.push(`${code}=${mapping}`);
  }
  if (entries.length < 1000) throw new Error(`CaseFolding.txt gave only ${entries.length} C and F entries`);
  return entries;
}

export function caseFoldingModule(entries: string[]): string {
  const lines: string[] = [];
  for (let at = 0; at < entries.length; at += 12) lines.push(`  ${JSON.stringify(entries.slice(at, at + 12).join(";"))},`);
  return `// GENERATED by scripts/generate-case-folding.ts from Unicode ${UNICODE_VERSION} CaseFolding.txt (statuses C and F) - do not edit; run: bun run generate:case-folding

export const CASE_FOLDING_UNICODE_VERSION = ${JSON.stringify(UNICODE_VERSION)};

/** Full case folding: \`<code point>=<its folding>\` in hex, code points of a folding separated by spaces, entries by \`;\`. */
export const CASE_FOLDING_DATA = [
${lines.join("\n")}
].join(";");
`;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const sourceAt = args.indexOf("--source");
  const source = sourceAt >= 0 ? readFileSync(args[sourceAt + 1]!, "utf8") : await (async () => {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error(`${SOURCE_URL}: HTTP ${response.status}`);
    return await response.text();
  })();
  const module = caseFoldingModule(caseFoldingEntries(source));
  if (args.includes("--check")) {
    if (readFileSync(OUTPUT, "utf8") !== module) {
      console.error(`${OUTPUT} is stale: run bun run generate:case-folding`);
      process.exit(1);
    }
  } else writeFileSync(OUTPUT, module);
}
